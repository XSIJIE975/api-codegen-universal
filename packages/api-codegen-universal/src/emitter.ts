// 辅助函数
// ===================================================================================

/** 解析 ref / 类型文本中的基础接口名：`A[]` → A，`Base<A, B[]>` → Base, A, B */
function extractBaseNames(ref: string): string[] {
  const names: string[] = [];
  // 把数组/泛型符号都替换为分隔符，逐层拆出全部基础名
  const cleaned = ref.replace(/[[\]<>]/g, ',');
  for (const part of cleaned.split(',')) {
    const name = part.trim();
    if (name) names.push(name);
  }
  return names;
}

/** 在代码文本中查找整词匹配的接口名 */
function hasWholeWord(text: string, name: string): boolean {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`\\b${escaped}\\b`).test(text);
}

/** 找到一段接口代码中引用的其他接口名 */
function findReferencedNames(code: string, nameSet: Set<string>): Set<string> {
  const found = new Set<string>();
  for (const name of nameSet) {
    // 跳过自身与" 定义名"（代码以 export ... <name> 开头）
    if (hasWholeWord(code, name)) {
      found.add(name);
    }
  }
  // 移除代码自身定义的名字
  const selfMatch = code.match(
    /export\s+(?:interface|type)\s+([A-Za-z0-9_$]+)/,
  );
  if (selfMatch && selfMatch[1]) found.delete(selfMatch[1]);
  return found;
}

/** POSIX 路径拼接 */
function posixJoin(...parts: string[]): string {
  return parts
    .map(toPosix)
    .filter((p) => p !== '')
    .join('/');
}

function toPosix(p: string): string {
  return p.replace(/\\/g, '/');
}

/**
 * 计算从 fromFile 到 toFile 的相对 import 路径（带 .js 后缀，ESM 友好）。
 * 两个参数都是相对 outDir 的 POSIX 路径。
 */
function relativeImport(fromFile: string, toFile: string): string {
  const fromParts = fromFile.split('/');
  fromParts.pop(); // 去掉文件名，留下目录
  const toParts = toFile.split('/');
  const fileName = toParts.pop()!.replace(/\.ts$/, '.js');

  let common = 0;
  while (
    common < fromParts.length &&
    common < toParts.length &&
    fromParts[common] === toParts[common]
  ) {
    common += 1;
  }
  const ups = fromParts.length - common;
  const downs = toParts.slice(common);
  const rel = [...Array.from({ length: ups }, () => '..'), ...downs];
  const joined =
    rel.length > 0 ? `${rel.join('/')}/${fileName}` : `./${fileName}`;
  // 同目录引用必须以 ./ 开头
  return joined.startsWith('.') ? joined : `./${joined}`;
}

async function writeFile(path: string, content: string): Promise<void> {
  const fs = await import('node:fs/promises');
  const nodePath = await import('node:path');
  await fs.mkdir(nodePath.dirname(path), { recursive: true });
  await fs.writeFile(path, content, 'utf-8');
}
